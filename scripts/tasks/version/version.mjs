#!/usr/bin/env node
// The mod and ElementNote share one version. `check` fails when the files
// disagree; `set <x.y.z>` writes it everywhere.
//   node scripts/tasks/version/version.mjs [check]
//   node scripts/tasks/version/version.mjs set 0.3.0
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const SEMVER = /^(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)(?:-[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/;

// Each entry finds the version in place, so formatting stays untouched.
const files = [
  ['Element/Info.json', /^(\s*"Version"\s*:\s*")([^"]*)(")/m],
  ['apps/element-note/package.json', /^( {2}"version"\s*:\s*")([^"]*)(")/m],
  ['apps/element-note/src-tauri/tauri.conf.json', /^( {2}"version"\s*:\s*")([^"]*)(")/m],
  ['apps/element-note/src-tauri/Cargo.toml', /^(version\s*=\s*")([^"]*)(")/m],
  ['apps/element-note/src-tauri/Cargo.lock', /^(name = "element-note"\nversion = ")([^"]*)(")/m],
  ['package-lock.json', /("apps\/element-note": \{\s*"name": "[^"]*",\s*"version": ")([^"]*)(")/],
  // Generated by `./scripts/run.sh desktop-licenses`; CI fails when it is stale.
  ['apps/element-note/THIRD_PARTY_LICENSES.txt', /^(- element-note )(\S+)()$/m],
];

function read() {
  return files.map(([file, pattern]) => {
    const text = fs.readFileSync(path.join(root, file), 'utf8');
    const match = pattern.exec(text);
    if (!match) throw new Error(`No version found in ${file}.`);
    return { file, pattern, text, version: match[2] };
  });
}

function fail(message) {
  console.error(`Error: ${message}`);
  process.exit(1);
}

const [command = 'check', value] = process.argv.slice(2);
const entries = read();

if (command === 'check') {
  const versions = new Set(entries.map((entry) => entry.version));
  if (versions.size !== 1) {
    for (const entry of entries) console.error(`  ${entry.version.padEnd(12)} ${entry.file}`);
    fail('The mod and ElementNote versions differ. Run ./scripts/run.sh version <x.y.z> to set one version everywhere.');
  }
  const [version] = versions;
  if (!SEMVER.test(version)) fail(`${version} is not a version like 1.2.3.`);
  console.log(version);
} else if (command === 'set') {
  if (!value || !SEMVER.test(value)) fail('Give a version like 0.3.0: ./scripts/run.sh version 0.3.0');
  for (const entry of entries) {
    const text = entry.text.replace(entry.pattern, (_, before, _old, after) => `${before}${value}${after}`);
    fs.writeFileSync(path.join(root, entry.file), text);
  }
  console.log(`Set version ${value} in:`);
  for (const entry of entries) console.log(`  ${entry.file} (was ${entry.version})`);
} else {
  fail(`Unknown command: ${command}. Use check or set <x.y.z>.`);
}
